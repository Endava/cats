package com.endava.cats.command.triage;

import com.endava.cats.http.HttpMethod;
import com.endava.cats.util.JsonUtils;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.Operation;
import io.swagger.v3.oas.models.PathItem;
import org.apache.commons.lang3.StringUtils;
import org.apache.commons.lang3.Strings;

import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * Records {@code 2XX}-{@code 4XX} status codes observed during the run that the contract does not document (or that the
 * report flagged as undocumented when no contract is supplied) and renders them as an OpenAPI {@code paths} overlay.
 */
final class ContractDriftDetector {
    private static final Map<Integer, String> STATUS_DESCRIPTIONS = Map.ofEntries(
            Map.entry(200, "OK"), Map.entry(201, "Created"), Map.entry(202, "Accepted"), Map.entry(204, "No Content"),
            Map.entry(400, "Bad Request"), Map.entry(401, "Unauthorized"), Map.entry(403, "Forbidden"),
            Map.entry(404, "Not Found"), Map.entry(409, "Conflict"), Map.entry(415, "Unsupported Media Type"),
            Map.entry(422, "Unprocessable Entity"));

    private final OpenAPI openAPI;
    private final Map<String, Map<String, Set<Integer>>> undocumented = new TreeMap<>();

    ContractDriftDetector(OpenAPI openAPI) {
        this.openAPI = openAPI;
    }

    void observe(TriageTestCase testCase) {
        int code = testCase.statusCode();
        if (StringUtils.isAnyBlank(testCase.path(), testCase.method()) || code < 200 || code >= 500 || !isUndocumentedObservation(testCase)) {
            return;
        }
        undocumented.computeIfAbsent(testCase.path(), _ -> new TreeMap<>())
                .computeIfAbsent(testCase.method().toLowerCase(Locale.ROOT), _ -> new TreeSet<>())
                .add(code);
    }

    boolean isUndocumented(TriageTestCase testCase) {
        return undocumented.getOrDefault(testCase.path(), Map.of())
                .getOrDefault(testCase.method().toLowerCase(Locale.ROOT), Set.of())
                .contains(testCase.statusCode());
    }

    String renderPatch() {
        if (undocumented.isEmpty()) {
            return "# No undocumented status codes detected\npaths: {}\n";
        }
        StringBuilder yaml = new StringBuilder("# OpenAPI contract patch generated by `cats triage`\npaths:\n");
        undocumented.forEach((path, byMethod) -> appendPath(yaml, path, byMethod));
        return yaml.toString();
    }

    private static void appendPath(StringBuilder yaml, String path, Map<String, Set<Integer>> byMethod) {
        yaml.append("  ").append(path).append(":\n");
        byMethod.forEach((method, codes) -> appendOperation(yaml, method, codes));
    }

    private static void appendOperation(StringBuilder yaml, String method, Set<Integer> codes) {
        yaml.append("    ").append(method).append(":\n      responses:\n");
        codes.forEach(code -> yaml.append("        '").append(code).append("':\n          description: ")
                .append(JsonUtils.GSON_NO_PRETTY_PRINTING.toJson(STATUS_DESCRIPTIONS.getOrDefault(code, "HTTP " + code))).append('\n'));
    }

    private boolean isUndocumentedObservation(TriageTestCase testCase) {
        return openAPI != null && openAPI.getPaths() != null
                ? isUndocumentedInContract(testCase)
                : isReportedAsUndocumented(testCase);
    }

    private boolean isUndocumentedInContract(TriageTestCase testCase) {
        PathItem pathItem = openAPI.getPaths().get(testCase.path());
        Optional<Operation> operation = Optional.ofNullable(pathItem)
                .flatMap(item -> HttpMethod.fromString(testCase.method()).map(method -> HttpMethod.getOperation(method, item)));
        return operation.map(Operation::getResponses)
                .map(responses -> responses.keySet().stream().noneMatch(key -> documents(key, testCase.statusCode())))
                .orElse(false);
    }

    private static boolean documents(String responseKey, int code) {
        return responseKey.equalsIgnoreCase(String.valueOf(code))
                || responseKey.equalsIgnoreCase((code / 100) + "XX")
                || "default".equalsIgnoreCase(responseKey);
    }

    private static boolean isReportedAsUndocumented(TriageTestCase testCase) {
        return Strings.CI.contains(testCase.testCase().getResultReason(), "undocumented")
                || Strings.CI.contains(testCase.testCase().getResultDetails(), "undocumented");
    }
}
