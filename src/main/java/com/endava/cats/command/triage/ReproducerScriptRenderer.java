package com.endava.cats.command.triage;

import java.util.LinkedHashSet;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.IntStream;

/**
 * Renders one minimal {@code curl} reproducer per root-cause cluster as a bash script. Masked report values
 * ({@code $$Authorization}) are expanded from the environment, and the script fails fast with a hint when they are unset.
 * All comment text is flattened to a single line so response content can never inject shell commands.
 */
public final class ReproducerScriptRenderer {
    private static final Pattern SHELL_VARIABLE = Pattern.compile("\\$\\{(\\w+)}");

    private ReproducerScriptRenderer() {
    }

    public static String render(TriageReport report) {
        StringBuilder script = new StringBuilder("#!/usr/bin/env bash\nset -euo pipefail\n\n")
                .append("# Minimal Root-Cause Reproducers generated by `cats triage`\n")
                .append("# Clusters: %d (from %d failing tests)".formatted(report.totalClusters(), report.totalErrors())).append('\n');
        requiredVariables(report).forEach(variable -> script.append(": \"${%s:?export %s=<value> before running; it is masked in the CATS report}\""
                .formatted(variable, variable)).append('\n'));
        script.append('\n');
        IntStream.range(0, report.clusters().size())
                .forEach(index -> appendCluster(script, index + 1, report.clusters().get(index)));
        return script.toString();
    }

    private static Set<String> requiredVariables(TriageReport report) {
        return report.clusters().stream()
                .flatMap(cluster -> SHELL_VARIABLE.matcher(cluster.curlReproducer()).results())
                .map(match -> match.group(1))
                .collect(Collectors.toCollection(LinkedHashSet::new));
    }

    private static void appendCluster(StringBuilder script, int index, RootCauseCluster cluster) {
        script.append("# ").append(ReportText.singleLine("%d. [%s] %s -> HTTP %d (%d tests: %s)".formatted(index, cluster.category(),
                        cluster.operation(), cluster.statusCode(), cluster.occurrences(), String.join(", ", cluster.sampleTestIds()))))
                .append('\n')
                .append("# Diagnosis: ").append(ReportText.singleLine(cluster.diagnosis())).append('\n')
                .append(cluster.curlReproducer()).append("\n\n");
    }
}
