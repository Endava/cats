package com.endava.cats.command.triage;

import java.util.LinkedHashSet;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.IntStream;

/**
 * Renders one minimal {@code curl} reproducer per problem occurrence (one problem on one operation) as a bash script. Masked report values
 * ({@code $$Authorization}) are expanded from the environment, and the script fails fast with a hint when they are unset.
 * All comment text is flattened to a single line so response content can never inject shell commands.
 */
public final class ReproducerScriptRenderer {
    private static final Pattern SHELL_VARIABLE = Pattern.compile("\\$\\{(\\w+)}");

    private ReproducerScriptRenderer() {
    }

    public static String render(TriageReport report) {
        StringBuilder script = new StringBuilder("#!/usr/bin/env bash\nset -euo pipefail\n\n")
                .append("# Minimal reproducers generated by `cats triage`, one per problem occurrence\n")
                .append("# Problems: %d, occurrences: %d (from %d errors and %d warnings)".formatted(report.totalProblems(),
                        report.totalOccurrences(), report.totalErrors(), report.totalWarnings())).append('\n');
        requiredVariables(report).forEach(variable -> script.append(": \"${%s:?export %s=<value> before running; it is masked in the CATS report}\""
                .formatted(variable, variable)).append('\n'));
        script.append('\n');
        IntStream.range(0, report.problems().size())
                .forEach(index -> report.problems().get(index).occurrences()
                        .forEach(occurrence -> appendOccurrence(script, index + 1, report.problems().get(index), occurrence)));
        return script.toString();
    }

    private static Set<String> requiredVariables(TriageReport report) {
        return report.problems().stream().flatMap(problem -> problem.occurrences().stream())
                .flatMap(occurrence -> SHELL_VARIABLE.matcher(occurrence.curlReproducer()).results())
                .map(match -> match.group(1))
                .collect(Collectors.toCollection(LinkedHashSet::new));
    }

    private static void appendOccurrence(StringBuilder script, int rank, TriageProblem problem, TriageOccurrence occurrence) {
        script.append("# ").append(ReportText.singleLine("Problem %d (%s): %s".formatted(rank, problem.problemId(), problem.title()))).append('\n')
                .append("# ").append(ReportText.singleLine("[%s] %s -> HTTP %s (%d tests: %s)".formatted(occurrence.category(),
                        occurrence.operation(), occurrence.statusCodes(), occurrence.testCount(), String.join(", ", occurrence.sampleTestIds()))))
                .append('\n')
                .append("# Diagnosis: ").append(ReportText.singleLine(occurrence.diagnosis())).append('\n')
                .append(occurrence.curlReproducer()).append("\n\n");
    }
}
